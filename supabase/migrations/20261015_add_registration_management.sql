-- Public availability contains counts only and never applicant data.
create function public.get_event_group_availability(p_event_group_id bigint)
returns table (
  schedule_id bigint,
  capacity integer,
  registered_count bigint,
  remaining_capacity integer,
  is_full boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    s.id as schedule_id,
    s.capacity,
    count(ri.id)::bigint as registered_count,
    greatest(s.capacity - count(ri.id)::integer, 0) as remaining_capacity,
    count(ri.id) >= s.capacity as is_full
  from public.schedules as s
  left join public.registration_items as ri
    on ri.schedule_id = s.id
    and ri.status = 'active'
  where s.event_group_id = p_event_group_id
    and s.capacity is not null
  group by s.id, s.capacity, s.date, s.start_time
  order by s.date, s.start_time, s.id;
$$;

-- A proxy registration may be accepted after public registration has closed,
-- but it always uses the same capacity-locking helper and never overbooks.
create function public.admin_create_registration(
  p_event_group_id bigint,
  p_name text,
  p_contact text,
  p_notes text,
  p_schedule_ids bigint[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'administrator access is required';
  end if;

  perform public.create_registration(
    p_event_group_id,
    p_name,
    p_contact,
    p_notes,
    p_schedule_ids,
    false
  );
end;
$$;

-- Administrators use the same capacity-locking helper to add classes to an
-- existing application. Removing a class is a cancellation, so history remains.
create function public.admin_add_registration_items(
  p_registration_id bigint,
  p_schedule_ids bigint[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event_group_id bigint;
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'administrator access is required';
  end if;

  select r.event_group_id into v_event_group_id
  from public.registrations as r
  where r.id = p_registration_id
  for update;

  if not found then
    raise exception using errcode = '22023', message = 'registration does not exist';
  end if;

  perform public.add_registration_items(p_registration_id, v_event_group_id, p_schedule_ids);
end;
$$;

-- Class-level cancellation retains the row and immediately frees one seat.
create function public.admin_cancel_registration_item(p_registration_item_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_schedule_id bigint;
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'administrator access is required';
  end if;

  -- Read the class first without locking the item, then take the same schedule
  -- row lock used by add_registration_items(). This keeps all capacity changes
  -- serialized by schedule ID and avoids an item-lock -> schedule-lock cycle.
  select ri.schedule_id into v_schedule_id
  from public.registration_items as ri
  where ri.id = p_registration_item_id
    and ri.status = 'active';

  if not found then
    raise exception using errcode = '22023', message = 'active registration item does not exist';
  end if;

  perform 1
  from public.schedules as s
  where s.id = v_schedule_id
  for update;

  if not found then
    raise exception using errcode = '22023', message = 'schedule does not exist';
  end if;

  update public.registration_items
  set status = 'cancelled',
      cancelled_at = now()
  where id = p_registration_item_id
    and status = 'active';

  if not found then
    raise exception using errcode = '22023', message = 'active registration item does not exist';
  end if;
end;
$$;

-- Contact and notes can be corrected without changing class capacity.
create function public.admin_update_registration_details(
  p_registration_id bigint,
  p_name text,
  p_contact text,
  p_notes text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'administrator access is required';
  end if;

  if p_name is null or char_length(btrim(p_name)) not between 1 and 100 then
    raise exception using errcode = '22023', message = 'a valid name is required';
  end if;

  if p_contact is null or char_length(btrim(p_contact)) not between 1 and 254 then
    raise exception using errcode = '22023', message = 'a valid contact is required';
  end if;

  if p_notes is not null and char_length(p_notes) > 2000 then
    raise exception using errcode = '22023', message = 'notes are too long';
  end if;

  update public.registrations
  set name = btrim(p_name),
      contact = btrim(p_contact),
      notes = nullif(btrim(p_notes), ''),
      updated_at = now()
  where id = p_registration_id;

  if not found then
    raise exception using errcode = '22023', message = 'registration does not exist';
  end if;
end;
$$;

