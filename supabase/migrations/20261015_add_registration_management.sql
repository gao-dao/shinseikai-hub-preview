-- Participation registration management for event groups and schedule classes.
-- This migration is intended for a new schema change after the initial baseline.
-- Do not run it against Supabase until it has been reviewed.

begin;

create table public.event_groups (
  id bigint generated by default as identity primary key,
  title text not null,
  description text null,
  registration_open boolean not null default false,
  created_at timestamptz not null default now(),
  constraint event_groups_title_not_blank check (char_length(btrim(title)) between 1 and 200),
  constraint event_groups_description_length check (description is null or char_length(description) <= 3000)
);

-- Existing schedules remain valid and visible without an event group.
alter table public.schedules
  add column event_group_id bigint null,
  add column capacity integer null,
  add column registration_enabled boolean not null default false,
  add constraint schedules_event_group_id_fkey
    foreign key (event_group_id) references public.event_groups(id) on delete set null,
  add constraint schedules_capacity_positive
    check (capacity is null or capacity > 0),
  add constraint schedules_registration_requires_capacity
    check (not registration_enabled or capacity is not null),
  add constraint schedules_id_event_group_id_key unique (id, event_group_id);

create table public.registrations (
  id bigint generated by default as identity primary key,
  event_group_id bigint not null references public.event_groups(id) on delete restrict,
  name text not null,
  contact text not null,
  notes text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint registrations_name_not_blank check (char_length(btrim(name)) between 1 and 100),
  constraint registrations_contact_not_blank check (char_length(btrim(contact)) between 1 and 254),
  constraint registrations_notes_length check (notes is null or char_length(notes) <= 2000),
  constraint registrations_id_event_group_id_key unique (id, event_group_id)
);

-- A selected class is retained as a separate item so class-level cancellations
-- remain in history while no longer consuming capacity.
create table public.registration_items (
  id bigint generated by default as identity primary key,
  registration_id bigint not null,
  event_group_id bigint not null references public.event_groups(id) on delete restrict,
  schedule_id bigint not null,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  cancelled_at timestamptz null,
  constraint registration_items_status_check check (status in ('active', 'cancelled')),
  constraint registration_items_cancelled_at_check check (
    (status = 'active' and cancelled_at is null)
    or (status = 'cancelled' and cancelled_at is not null)
  ),
  constraint registration_items_registration_group_fkey
    foreign key (registration_id, event_group_id)
    references public.registrations(id, event_group_id) on delete restrict,
  constraint registration_items_schedule_group_fkey
    foreign key (schedule_id, event_group_id)
    references public.schedules(id, event_group_id) on delete restrict
);

create index schedules_event_group_schedule_order_idx
  on public.schedules (event_group_id, date, start_time, id);
create index registrations_event_group_created_at_idx
  on public.registrations (event_group_id, created_at desc);
create index registration_items_registration_id_idx
  on public.registration_items (registration_id);
create index registration_items_active_schedule_id_idx
  on public.registration_items (schedule_id) where status = 'active';
create unique index registration_items_one_active_class_per_registration_idx
  on public.registration_items (registration_id, schedule_id) where status = 'active';

alter table public.event_groups enable row level security;
alter table public.registrations enable row level security;
alter table public.registration_items enable row level security;

-- Event group metadata is public because public schedule pages need it.
create policy "anyone can view event groups" on public.event_groups
  for select to anon, authenticated using (true);
create policy "admins can insert event groups" on public.event_groups
  for insert to authenticated with check ((select public.is_admin()));
create policy "admins can update event groups" on public.event_groups
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "admins can delete event groups" on public.event_groups
  for delete to authenticated using ((select public.is_admin()));

-- Applicant data is never visible to anon users or non-admin authenticated users.
create policy "admins can view registrations" on public.registrations
  for select to authenticated using ((select public.is_admin()));
create policy "admins can view registration items" on public.registration_items
  for select to authenticated using ((select public.is_admin()));

-- Explicit Data API privileges. RLS is still the final row-level guard.
grant select on table public.event_groups to anon, authenticated;
grant insert, update, delete on table public.event_groups to authenticated;
grant usage, select on sequence public.event_groups_id_seq to authenticated;

revoke all on table public.registrations from anon, authenticated;
revoke all on table public.registration_items from anon, authenticated;
grant select on table public.registrations to authenticated;
grant select on table public.registration_items to authenticated;

-- Do not allow a schedule capacity to be reduced below its active registrations.
-- The schedule row lock also serializes this check with new registration attempts.
create function public.enforce_schedule_capacity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_active_count integer;
begin
  select count(*) into v_active_count
  from public.registration_items as ri
  where ri.schedule_id = new.id
    and ri.status = 'active';

  if new.capacity is null and v_active_count > 0 then
    raise exception using errcode = '23514', message = 'capacity cannot be removed while active registrations exist';
  end if;

  if new.capacity is not null and v_active_count > new.capacity then
    raise exception using errcode = '23514', message = 'capacity cannot be lower than active registrations';
  end if;

  return new;
end;
$$;

create trigger schedules_enforce_capacity_before_change
before insert or update of capacity on public.schedules
for each row execute function public.enforce_schedule_capacity();

-- Internal helper shared by public submissions and administrator additions.
-- Every multi-class operation locks schedule rows in ascending ID order, which
-- prevents overbooking and makes deadlocks between multi-class requests unlikely.
create function public.add_registration_items(
  p_registration_id bigint,
  p_event_group_id bigint,
  p_schedule_ids bigint[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_schedule record;
  v_schedule_id bigint;
  v_locked_count integer := 0;
  v_active_count integer;
begin
  if p_schedule_ids is null or cardinality(p_schedule_ids) = 0 then
    raise exception using errcode = '22023', message = 'at least one class must be selected';
  end if;

  if array_position(p_schedule_ids, null) is not null then
    raise exception using errcode = '22023', message = 'class ids cannot contain null';
  end if;

  if (
    select count(*) <> count(distinct requested.schedule_id)
    from unnest(p_schedule_ids) as requested(schedule_id)
  ) then
    raise exception using errcode = '22023', message = 'duplicate class ids are not allowed';
  end if;

  for v_schedule_id in
    select requested.schedule_id
    from unnest(p_schedule_ids) as requested(schedule_id)
    order by requested.schedule_id
  loop
    select s.id, s.event_group_id, s.capacity, s.registration_enabled
      into v_schedule
      from public.schedules as s
      where s.id = v_schedule_id
      for update;

    if not found then
      raise exception using errcode = '22023', message = 'one or more selected classes do not exist';
    end if;

    v_locked_count := v_locked_count + 1;

    if v_schedule.event_group_id is distinct from p_event_group_id then
      raise exception using errcode = '22023', message = 'classes must belong to the same event group';
    end if;

    if not v_schedule.registration_enabled or v_schedule.capacity is null then
      raise exception using errcode = '22023', message = 'class is not accepting registrations';
    end if;

    select count(*) into v_active_count
    from public.registration_items as ri
    where ri.schedule_id = v_schedule.id
      and ri.status = 'active';

    if v_active_count >= v_schedule.capacity then
      raise exception using errcode = 'P0001', message = 'one or more selected classes are full';
    end if;
  end loop;

  if v_locked_count <> cardinality(p_schedule_ids) then
    raise exception using errcode = '22023', message = 'one or more selected classes do not exist';
  end if;

  insert into public.registration_items (registration_id, event_group_id, schedule_id)
  select p_registration_id, p_event_group_id, requested.schedule_id
  from unnest(p_schedule_ids) as requested(schedule_id);
end;
$$;

-- Internal creation helper. p_require_open is true for a public application
-- and false for a verified administrator's proxy registration.
create function public.create_registration(
  p_event_group_id bigint,
  p_name text,
  p_contact text,
  p_notes text,
  p_schedule_ids bigint[],
  p_require_open boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_registration_id bigint;
  v_registration_open boolean;
begin
  if p_name is null or char_length(btrim(p_name)) not between 1 and 100 then
    raise exception using errcode = '22023', message = 'a valid name is required';
  end if;

  if p_contact is null or char_length(btrim(p_contact)) not between 1 and 254 then
    raise exception using errcode = '22023', message = 'a valid contact is required';
  end if;

  if p_notes is not null and char_length(p_notes) > 2000 then
    raise exception using errcode = '22023', message = 'notes are too long';
  end if;

  select eg.registration_open into v_registration_open
  from public.event_groups as eg
  where eg.id = p_event_group_id
  for update;

  if not found then
    raise exception using errcode = '22023', message = 'event group does not exist';
  end if;

  if p_require_open and not v_registration_open then
    raise exception using errcode = '22023', message = 'registration is closed';
  end if;

  insert into public.registrations (event_group_id, name, contact, notes)
  values (p_event_group_id, btrim(p_name), btrim(p_contact), nullif(btrim(p_notes), ''))
  returning id into v_registration_id;

  perform public.add_registration_items(v_registration_id, p_event_group_id, p_schedule_ids);
end;
$$;

