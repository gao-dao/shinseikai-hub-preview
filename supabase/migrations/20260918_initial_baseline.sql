-- Initial baseline of the application-owned Production Supabase database configuration as of 2026-09-18.
-- This file records the application-owned schema and policies for future reference and reconstruction.
-- In Production on 2026-09-18, RLS is enabled on public.profiles, public.schedules, and public.videos;
-- FORCE ROW LEVEL SECURITY is disabled on all three tables.
-- This baseline explicitly grants the Data API privileges required by the application.
-- Supabase-managed mechanisms such as rls_auto_enable, ensure_rls, and other event triggers are outside the
-- scope of this application-owned baseline.
-- Do not execute this file directly against the existing Production database.

create table public.profiles (
  id uuid not null,
  role text not null default 'member',
  primary key (id),
  foreign key (id) references auth.users (id)
);

create table public.schedules (
  id bigint generated by default as identity not null,
  title text not null,
  date text not null,
  start_time text null,
  end_time text null,
  location text not null,
  type text not null,
  created_at timestamptz null default now(),
  primary key (id),
  check (type in ('稽古会', '一般参加'))
);

create table public.videos (
  id bigint generated by default as identity not null,
  title text not null,
  description text null,
  url text not null,
  duration text null,
  tag text null,
  created_at timestamptz null default now(),
  primary key (id)
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

alter table public.profiles enable row level security;
alter table public.schedules enable row level security;
alter table public.videos enable row level security;

create policy "authenticated users can view own profile"
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

create policy "anyone can view schedules"
  on public.schedules
  for select
  to anon, authenticated
  using (true);

create policy "admins can insert schedules"
  on public.schedules
  for insert
  to authenticated
  with check ((select public.is_admin()));

create policy "admins can update schedules"
  on public.schedules
  for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "admins can delete schedules"
  on public.schedules
  for delete
  to authenticated
  using ((select public.is_admin()));

create policy "authenticated users can view videos"
  on public.videos
  for select
  to authenticated
  using (true);

create policy "admins can insert videos"
  on public.videos
  for insert
  to authenticated
  with check ((select public.is_admin()));

create policy "admins can update videos"
  on public.videos
  for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "admins can delete videos"
  on public.videos
  for delete
  to authenticated
  using ((select public.is_admin()));

grant select on table public.profiles to authenticated;
grant select on table public.profiles to service_role;

grant select on table public.schedules to anon, authenticated;
grant insert, update, delete on table public.schedules to authenticated;
grant usage on sequence public.schedules_id_seq to authenticated;

grant select, insert, update, delete on table public.videos to authenticated;
grant usage on sequence public.videos_id_seq to authenticated;
